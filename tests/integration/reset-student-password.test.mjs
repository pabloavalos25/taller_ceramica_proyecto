import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import pg from 'pg';
import { hashPassword, verifyPassword } from '../../src/auth/passwords.mjs';
import { createSession, getSession } from '../../src/auth/sessions.mjs';
import { createAuthHandlers } from '../../src/auth/http-handlers.mjs';
import { resetStudentPassword } from '../../src/auth/reset-student-password.mjs';
const url = process.env.TEST_DATABASE_URL;
if (!url) throw new Error('TEST_DATABASE_URL debe apuntar a una base de pruebas aislada');

test('administrator resets student password with audit and revokes prior sessions', async () => {
  const schema = `suyai_test_${randomUUID().replaceAll('-', '')}`;
  const root = new pg.Client({ connectionString: url }); await root.connect(); await root.query(`CREATE SCHEMA "${schema}"`);
  const pool = new pg.Pool({ connectionString: url, options: `-c search_path=${schema}` });
  try {
    for (const file of ['001_initial.sql','006_auth_sessions.sql','008_password_change_throttle.sql','009_student_password_reset.sql','025_admin_profiles.sql']) await pool.query(await readFile(new URL(`../../db/migrations/${file}`, import.meta.url), 'utf8'));
    const hash = await hashPassword('contraseña original 123');
    const admin = (await pool.query("INSERT INTO users(email,password_hash,role,must_change_password) VALUES ('admin@example.com',$1,'ADMIN',false) RETURNING id", [hash])).rows[0].id; await pool.query("INSERT INTO admin_profiles(user_id,display_name,access_level) VALUES ($1,'Principal','PRINCIPAL')",[admin]);
    const student = (await pool.query("INSERT INTO users(email,password_hash,role,must_change_password) VALUES ('ana@example.com',$1,'USER',false) RETURNING id", [hash])).rows[0].id;
    await pool.query("INSERT INTO student_profiles(user_id,full_name,enrolled_on,active) VALUES ($1,'Ana','2026-11-25',false)", [student]);
    const adminToken = await createSession(pool, admin); const studentToken = await createSession(pool, student);
    const input = { actorToken: adminToken, studentId: student, temporaryPassword: 'contraseña temporal 456', reason: 'Olvidó su contraseña' };
    await assert.rejects(resetStudentPassword(pool, { ...input, actorToken: studentToken }), /autoriz/i);
    await assert.rejects(resetStudentPassword(pool, { ...input, reason: ' ' }), /motivo/i);
    await assert.rejects(resetStudentPassword(pool, { ...input, studentId: admin }), /alumna/i);
    await assert.rejects(resetStudentPassword(pool, { ...input, reason: 'contraseña temporal 456' }), /motivo/i);
    await pool.query('UPDATE users SET must_change_password = true WHERE id=$1', [admin]);
    await assert.rejects(resetStudentPassword(pool, input), /autoriz/i);
    await pool.query('UPDATE users SET must_change_password = false WHERE id=$1', [admin]);
    await pool.query(`CREATE FUNCTION fail_reset_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'forced audit failure'; END $$`);
    await pool.query('CREATE TRIGGER force_reset_audit_failure BEFORE INSERT ON student_password_reset_events FOR EACH ROW EXECUTE FUNCTION fail_reset_audit()');
    await assert.rejects(resetStudentPassword(pool, input), /forced audit failure/);
    assert.notEqual(await getSession(pool, studentToken), null);
    const before = (await pool.query('SELECT password_hash FROM users WHERE id=$1', [student])).rows[0];
    assert.equal(await verifyPassword('contraseña original 123', before.password_hash), true);
    await pool.query('DROP TRIGGER force_reset_audit_failure ON student_password_reset_events');
    await resetStudentPassword(pool, input);
    assert.equal(await getSession(pool, studentToken), null);
    const newSession = await createSession(pool, student);
    assert.equal((await getSession(pool, newSession)).mustChangePassword, true);
    const updated = (await pool.query('SELECT password_hash, must_change_password FROM users WHERE id=$1', [student])).rows[0];
    assert.equal(updated.must_change_password, true);
    assert.equal(await verifyPassword('contraseña temporal 456', updated.password_hash), true);
    assert.equal(await verifyPassword('contraseña original 123', updated.password_hash), false);
    const events = (await pool.query('SELECT actor_id, student_id, reason FROM student_password_reset_events')).rows;
    assert.deepEqual(events, [{ actor_id: admin, student_id: student, reason: 'Olvidó su contraseña' }]);
    assert.equal(JSON.stringify(events).includes('contraseña temporal 456'), false);
    const handlers = createAuthHandlers({ origin: 'https://suyai.example', production: true, resetStudentPassword: (data) => resetStudentPassword(pool, data) });
    const headers = { origin: 'https://suyai.example', 'content-type': 'application/json' };
    const body = JSON.stringify({ studentId: student, temporaryPassword: 'otra temporal segura 789', reason: 'Segunda solicitud' });
    const unauth = await handlers.resetStudentPassword(new Request('https://suyai.example/api', { method: 'POST', headers: { ...headers, cookie: `__Host-suyai_session=${newSession}` }, body }));
    assert.equal(unauth.status, 403);
    const reset = await handlers.resetStudentPassword(new Request('https://suyai.example/api', { method: 'POST', headers: { ...headers, cookie: `__Host-suyai_session=${adminToken}` }, body }));
    assert.equal(reset.status, 200); assert.equal((await reset.text()).includes('otra temporal segura 789'), false);
    assert.equal(await getSession(pool, newSession), null);
    assert.equal((await pool.query('SELECT count(*)::int AS count FROM student_password_reset_events')).rows[0].count, 2);
  } finally { await pool.end(); await root.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); await root.end(); }
});
